#!/usr/bin/env python3
"""Build the banana2d test ROM: out/banana2d.nds.

Needs clang + ld.lld + llvm-objcopy (the ARM9 is built for armv5te; the ARM7 is a 4-byte halt loop).
The header follows the layout melonDS and DraStic boot: the ARM9 binary right after the header at
0x200 (so melonDS treats the ROM as homebrew, no secure area), the ARM7 after it, no logo.
"""
import math, os, struct, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")
os.makedirs(OUT, exist_ok=True)

# tables.h: a sine table in 4.12
sintab = [int(round(math.sin(i * 2 * math.pi / 256) * 4096)) for i in range(256)]
with open(os.path.join(HERE, "tables.h"), "w") as f:
    f.write("/* generated by build.py */\n")
    f.write("static const short sintab[256] = {%s};\n" % ",".join(map(str, sintab)))

LD = """ENTRY(_start)
SECTIONS {
  . = 0x02000000;
  .text : { *(.text.start) *(.text*) *(.rodata*) }
  .data : { *(.data*) }
  . = ALIGN(4);
  __bss_start = .;
  .bss : { *(.bss*) *(COMMON) }
  . = ALIGN(4);
  __bss_end = .;
  /DISCARD/ : { *(.ARM.exidx*) *(.ARM.extab*) }
}
"""
with open(os.path.join(OUT, "ld9.ld"), "w") as f: f.write(LD)

T = ["--target=armv5te-none-eabi", "-marm", "-mfloat-abi=soft"]
def run(cmd): subprocess.run(cmd, check=True, cwd=HERE)
run(["clang", *T, "-O2", "-fno-unwind-tables", "-fno-asynchronous-unwind-tables", "-ffreestanding", "-fno-builtin",
     "-nostdlib", "-Wall", "-Wno-unused-function", "-c", "main9.c", "-o", "out/main9.o"])
run(["clang", *T, "-c", "crt9.s", "-o", "out/crt9.o"])
run(["ld.lld", "-T", "out/ld9.ld", "out/crt9.o", "out/main9.o", "-o", "out/arm9.elf"])
run(["llvm-objcopy", "-O", "binary", "out/arm9.elf", "out/arm9.bin"])
arm9 = bytearray(open(os.path.join(OUT, "arm9.bin"), "rb").read())
arm9 += b"\0" * (-len(arm9) % 0x200)
# ARM7 stub: HALTCNT <- 0x80 in a loop (ldr/strb/b with the address in a literal)
arm7 = struct.pack("<5I", 0xE59F0008, 0xE3A01080, 0xE5C01001, 0xEAFFFFFB, 0x04000300)
arm7 += b"\0" * (-len(arm7) % 0x200)

def crc16(data, crc=0xFFFF):
    for b in data:
        crc ^= b
        for _ in range(8): crc = (crc >> 1) ^ 0xA001 if crc & 1 else crc >> 1
    return crc

a9off = 0x200
a7off = a9off + len(arm9)
body = bytearray(0x200) + arm9 + arm7
body += b"\0" * (-len(body) % 0x200)
h = bytearray(0x200)
h[0:12] = b"BANANA2D".ljust(12, b"\0"); h[12:16] = b"####"; h[16:18] = b"00"
h[0x14] = 0                                              # 128 KB
struct.pack_into("<8I", h, 0x20, a9off, 0x02000000, 0x02000000, len(arm9),
                 a7off, 0x02380000, 0x02380000, len(arm7))
struct.pack_into("<2I", h, 0x60, 0x00586000, 0x001808F8)
struct.pack_into("<2I", h, 0x80, len(body), 0x200)
struct.pack_into("<H", h, 0x15E, crc16(h[:0x15E]))
body[0:0x200] = h
if len(body) < 0x20000: body += b"\xff" * (0x20000 - len(body))
out = os.path.join(OUT, "banana2d.nds")
with open(out, "wb") as f: f.write(body)
print("%s: %d bytes, ARM9 %d bytes" % (out, len(body), len(arm9)))
